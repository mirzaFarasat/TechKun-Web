import '@radix-ui/themes/styles.css';
import type { Metadata } from "next";
import localFont from "next/font/local";
import "./globals.scss";
import Navbar from "./components/Navbar";
import { Theme } from '@radix-ui/themes';
import Footer from "./Footer";
import NextTopLoader from 'nextjs-toploader';
import CookieConsent from './components/CookieConsent';
import MeetUsAtGitex from './meet-us-at-gitex';
import ComingSoon from './coming-soon/ComingSoon';

// Site-wide "coming soon" takeover. Set NEXT_PUBLIC_MAINTENANCE_MODE=false to bring the live site back.
const IS_COMING_SOON = process.env.NEXT_PUBLIC_MAINTENANCE_MODE !== 'false';

const geistSans = localFont({
    src: "./fonts/GeistVF.woff",
    variable: "--font-geist-sans",
    weight: "100 900",
});
const geistMono = localFont({
    src: "./fonts/GeistMonoVF.woff",
    variable: "--font-geist-mono",
    weight: "100 900",
});

export const metadata: Metadata = IS_COMING_SOON
    ? {
        title: "TechKun — Coming Soon",
        description: "TechKun's new website is launching soon. We're building something great.",
    }
    : {
        title: "TechKun",
        description: "Generated by create next app",
    };

export default function RootLayout({
    children,
}: Readonly<{
    children: React.ReactNode;
}>) {
    if (IS_COMING_SOON) {
        return (
            <html lang="en">
                <body className={`${geistSans.variable} ${geistMono.variable} antialiased`}>
                    <ComingSoon />
                </body>
            </html>
        );
    }

    return (
        <html lang="en">
            <body
                className={`${geistSans.variable} ${geistMono.variable} antialiased`}>
                <Theme>
                    <MeetUsAtGitex />
                    <Navbar />
                    <NextTopLoader />
                    <main className='overflow-hidden'>{children}</main>
                    <CookieConsent />
                </Theme>
                <Footer />
            </body>
        </html>
    );
}
